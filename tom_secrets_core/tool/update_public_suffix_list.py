"""Writes lib/src/public_suffix_list.g.dart from the Public Suffix List.

    tool/update_public_suffix_list.py [list.dat]

Without an argument the list is fetched from
https://publicsuffix.org/list/public_suffix_list.dat (the one place the
list's maintainers ask it to be pulled from). The rules of both sections
(ICANN and private) are kept, comments and blank lines dropped, and every
non-ASCII label written as punycode (`xn--...`), the form the matcher
normalises hosts to. The generated file carries the list's licence notice
(Mozilla Public License 2.0) and its version. Run by hand when the list
should be refreshed, then commit the generated file.
"""
from __future__ import annotations

import pathlib
import sys
import urllib.request

URL = 'https://publicsuffix.org/list/public_suffix_list.dat'
OUT = pathlib.Path(__file__).resolve().parent.parent / 'lib' / 'src' / 'public_suffix_list.g.dart'


def ascii_label(label: str) -> str:
    if label in ('*',) or label.isascii():
        return label.lower()
    return 'xn--' + label.lower().encode('punycode').decode('ascii')


def ascii_rule(rule: str) -> str:
    prefix = '!' if rule.startswith('!') else ''
    body = rule[1:] if prefix else rule
    return prefix + '.'.join(ascii_label(label) for label in body.split('.'))


def main() -> int:
    if len(sys.argv) > 1:
        text = pathlib.Path(sys.argv[1]).read_text(encoding='utf-8')
    else:
        with urllib.request.urlopen(URL) as answer:
            text = answer.read().decode('utf-8')
    version = ''
    rules: list[str] = []
    for line in text.splitlines():
        line = line.strip()
        if line.startswith('// VERSION:'):
            version = line[len('// VERSION:'):].strip()
        if not line or line.startswith('//'):
            continue
        rules.append(ascii_rule(line.split()[0]))
    if len(rules) < 5000:
        print(f'only {len(rules)} rules: not the list', file=sys.stderr)
        return 1
    body = '\n'.join(rules)
    if "'''" in body or '$' in body:
        print('a rule holds a character the raw string cannot', file=sys.stderr)
        return 1
    OUT.write_text(
        '// GENERATED by tool/update_public_suffix_list.py; do not edit.\n'
        '//\n'
        '// The Public Suffix List (https://publicsuffix.org/), its rules as\n'
        '// published, non-ASCII labels as punycode. The list is subject to the\n'
        '// terms of the Mozilla Public License, v. 2.0. If a copy of the MPL\n'
        '// was not distributed with this file, you can obtain one at\n'
        '// https://mozilla.org/MPL/2.0/.\n'
        '// ignore_for_file: lines_longer_than_80_chars\n'
        '\n'
        '/// The version of the Public Suffix List these rules are.\n'
        f"const String tomSecretsPublicSuffixListVersion = '{version}';\n"
        '\n'
        '/// The rules of the Public Suffix List, one per line.\n'
        f"const String tomSecretsPublicSuffixRules = r'''\n{body}\n''';\n",
        encoding='utf-8',
    )
    print(f'{OUT}: {len(rules)} rules, version {version}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
